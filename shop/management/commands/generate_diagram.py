from pathlib import Path

from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand
from django.db import models


OUTPUT_PATH = Path("docs/database-diagram.md")


FIELD_TYPE_MAP = {
    "AutoField": "int",
    "BigAutoField": "int",
    "BigIntegerField": "int",
    "BooleanField": "boolean",
    "CharField": "string",
    "DateField": "date",
    "DateTimeField": "datetime",
    "DecimalField": "decimal",
    "DurationField": "duration",
    "EmailField": "string",
    "FileField": "file",
    "FloatField": "float",
    "ImageField": "file",
    "IntegerField": "int",
    "JSONField": "json",
    "PositiveBigIntegerField": "int",
    "PositiveIntegerField": "int",
    "PositiveSmallIntegerField": "int",
    "SlugField": "string",
    "SmallIntegerField": "int",
    "TextField": "text",
    "TimeField": "time",
    "URLField": "string",
    "UUIDField": "uuid",
}


RELATIONSHIP_FIELDS = (
    models.ForeignKey,
    models.OneToOneField,
    models.ManyToManyField,
)


def get_project_models():
    """Return concrete, non-proxy models declared by local project apps."""
    base_dir = Path(settings.BASE_DIR).resolve()
    project_models = []

    for model in apps.get_models(include_auto_created=False):
        app_config = apps.get_app_config(model._meta.app_label)

        if model._meta.abstract or model._meta.proxy:
            continue

        try:
            app_path = Path(app_config.path).resolve()
            relative_app_path = app_path.relative_to(base_dir)
        except ValueError:
            continue

        if relative_app_path.parts and relative_app_path.parts[0].startswith("."):
            continue

        project_models.append(model)

    return sorted(project_models, key=lambda model: model.__name__.lower())


def mermaid_entity_name(model):
    return model.__name__


def mermaid_field_type(field):
    if field.many_to_many or field.many_to_one or field.one_to_one:
        return FIELD_TYPE_MAP.get(
            field.related_model._meta.pk.get_internal_type(), "string"
        )

    return FIELD_TYPE_MAP.get(field.get_internal_type(), "string")


def mermaid_field_line(field):
    markers = []

    if getattr(field, "primary_key", False):
        markers.append("PK")

    if isinstance(field, RELATIONSHIP_FIELDS):
        markers.append("FK")

    marker_text = f" {' '.join(markers)}" if markers else ""
    return f"        {mermaid_field_type(field)} {field.name}{marker_text}"


def model_fields(model, included_models):
    included_model_set = set(included_models)
    fields = []

    for field in list(model._meta.fields) + list(model._meta.local_many_to_many):
        if getattr(field, "auto_created", False) and not getattr(
            field, "primary_key", False
        ):
            continue

        if (
            isinstance(field, RELATIONSHIP_FIELDS)
            and field.related_model not in included_model_set
        ):
            continue

        fields.append(field)

    return sorted(fields, key=lambda field: (not field.primary_key, field.name.lower()))


def relationship_label(field):
    related_name = getattr(field.remote_field, "related_name", None)
    if related_name and related_name != "+":
        return related_name

    return field.name


def relationship_line(model, field):
    source = mermaid_entity_name(model)
    target = mermaid_entity_name(field.related_model)
    label = relationship_label(field)

    if isinstance(field, models.ManyToManyField):
        left, right = sorted([source, target])
        return f"    {left} }}o--o{{ {right} : {label}"

    if isinstance(field, models.OneToOneField):
        return f"    {target} ||--o| {source} : {label}"

    cardinality = "o|" if field.unique else "o{"
    return f"    {target} ||--{cardinality} {source} : {label}"


def model_relationships(model, included_models):
    included_model_set = set(included_models)
    relationships = []

    for field in list(model._meta.fields) + list(model._meta.local_many_to_many):
        if not isinstance(field, RELATIONSHIP_FIELDS):
            continue

        if field.related_model not in included_model_set:
            continue

        relationships.append(relationship_line(model, field))

    return relationships


def render_database_diagram():
    included_models = get_project_models()
    relationship_lines = []

    lines = [
        "# Database Diagram",
        "",
        "<!-- WARNING: This file is auto-generated by `python manage.py generate_diagram`. -->",
        "<!-- Do not edit this file manually. Regenerate it from Django models instead. -->",
        "",
        "```mermaid",
        "erDiagram",
    ]

    for model in included_models:
        lines.append(f"    {mermaid_entity_name(model)} {{")
        lines.extend(
            mermaid_field_line(field) for field in model_fields(model, included_models)
        )
        lines.append("    }")

        relationship_lines.extend(model_relationships(model, included_models))

    unique_relationship_lines = sorted(set(relationship_lines), key=str.lower)
    if unique_relationship_lines:
        lines.append("")
        lines.extend(unique_relationship_lines)

    lines.extend(["```", ""])
    return "\n".join(lines)


class Command(BaseCommand):
    help = "Generate docs/database-diagram.md from Django models."

    def add_arguments(self, parser):
        parser.add_argument(
            "--output",
            default=str(OUTPUT_PATH),
            help="Output path relative to BASE_DIR, or an absolute path.",
        )

    def handle(self, *args, **options):
        output_path = Path(options["output"])
        if not output_path.is_absolute():
            output_path = Path(settings.BASE_DIR) / output_path

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(render_database_diagram(), encoding="utf-8")

        self.stdout.write(self.style.SUCCESS(f"Generated {output_path}"))
