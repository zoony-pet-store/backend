from django.core.management import call_command

from shop.management.commands.generate_diagram import render_database_diagram


def test_generate_diagram_command_succeeds(tmp_path):
    output_path = tmp_path / "database-diagram.md"

    call_command("generate_diagram", output=str(output_path))

    output = output_path.read_text(encoding="utf-8")

    assert output.startswith("# Database Diagram")
    assert "erDiagram" in output
    assert "Do not edit this file manually" in output


def test_generate_diagram_output_is_deterministic():
    assert render_database_diagram() == render_database_diagram()


def test_generate_diagram_includes_relationships():
    output = render_database_diagram()

    assert "Category ||--o{ Product : products" in output
    assert "Customer ||--o| Cart : user" in output
    assert "Badge }o--o{ Product : products" in output


def test_generate_diagram_uses_mermaid_safe_attribute_types():
    output = render_database_diagram()

    assert "Brand brand FK" not in output
    assert "Category category FK" not in output
    assert "uuid brand FK" in output
    assert "uuid category FK" in output
